"""Publish reviewed equivalences without altering previously applied migrations."""
import json
import subprocess
import sys
from pathlib import Path

from build_media import normalize

HERE = Path(__file__).resolve().parent
MIGRATION = HERE.parent.parent.parent / 'supabase/migrations/20260927130000_deduplicate_gymvisual_exercises.sql'
catalog_path = HERE / 'exercises.json'
manifest_path = HERE / 'manifest.json'
source = {row['id']: row for row in json.loads((HERE / 'sources/gymvisual-media.json').read_text(encoding='utf-8'))}
equivalences = json.loads((HERE / 'sources/gymvisual-equivalences.json').read_text(encoding='utf-8'))
catalog = json.loads(catalog_path.read_text(encoding='utf-8'))
by_id = {row['id']: row for row in catalog}
assert len(by_id) == len(catalog)
assert set(equivalences) <= set(source)
assert all(target in by_id
           for source_id, target in equivalences.items())
assert all(not target.startswith('gymvisual-') or
           equivalences.get(target.removeprefix('gymvisual-'), target) == target
           for target in equivalences.values())

removed = {'gymvisual-' + source_id for source_id, target in equivalences.items()
           if target != 'gymvisual-' + source_id}
for source_id, target in equivalences.items():
    if target.startswith('gymvisual-'):
        continue
    aliases = by_id[target].setdefault('aliases', [])
    name = source[source_id]['name']
    if normalize(name) not in {normalize(alias) for alias in aliases}:
        aliases.append(name)
catalog = [row for row in catalog if row['id'] not in removed]
assert len(catalog) == 2125 - len(removed)
assert all(target in {row['id'] for row in catalog} for target in equivalences.values())
catalog_path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
manifest.update(catalogCount=len(catalog), gymvisualAddedCount=len(catalog) - 931,
                gymvisualDeduplicatedCount=len(removed), gymvisualReviewedMediaLinks=len(equivalences))
manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

subprocess.run([sys.executable, str(HERE / 'prepare_seed.py')], check=True)
seed_root = HERE.parent.parent / '.dart_tool/catalog-seed'
import hashlib
methods = json.loads((HERE / 'training-methods.json').read_text(encoding='utf-8'))
digest = hashlib.sha256(json.dumps([catalog, methods], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
version = '20260926-' + digest[:16]
out = seed_root / version
assert out.is_dir()
parts = [path.read_text(encoding='utf-8') for path in sorted(out.glob('[0-9][0-9][0-9]-*.sql'))]
activation = parts.pop()
assert activation.startswith('begin;') and activation.rstrip().endswith('commit;')
activation = activation.removeprefix('begin;').rstrip().removesuffix('commit;')
links = [dict(source_id=source_id, catalog_id=target) for source_id, target in equivalences.items()]
payload = json.dumps(links, ensure_ascii=False, separators=(',', ':'))
assert '$links$' not in payload
relink = f"""
update public.catalog_exercise_media as media
set catalog_exercise_id = row->>'catalog_id'
from jsonb_array_elements($links${payload}$links$::jsonb) as row
where media.id = row->>'source_id';
do $verify$ begin
  if (select count(*) from public.catalog_exercise_media
      where source_revision = '7455efae41b330c265e7cd4b78dfa848e7ce5ebd'
      and catalog_exercise_id in (select id from public.catalog_exercises where release_version='{version}')) <> 1324 then
    raise exception 'Incomplete GIF links in deduplicated catalog';
  end if;
end $verify$;
"""
MIGRATION.write_text(
    '-- Generated by valex_app/tool/exercise_catalog/deduplicate_gymvisual.py.\n'
    '-- Preserve all GIF rows while consolidating reviewed English/Portuguese equivalents.\n'
    + 'begin;\n' + '\n'.join(parts) + '\n' + relink + '\n' + activation + '\ncommit;\n',
    encoding='utf-8',
)
print(json.dumps(dict(version=version, catalogCount=len(catalog), removed=len(removed),
                      reviewedMediaLinks=len(equivalences), migration=str(MIGRATION))))
