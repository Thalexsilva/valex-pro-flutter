"""Produce deterministic SQL batches for a new, initially inactive release.

Run after generate.py. Apply the schema migration once, execute these numbered
batches in order, then activate only after verifying the complete upload.
No credentials, student records or network operations are used here.
"""
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
exercises = json.loads((HERE / 'exercises.json').read_text(encoding='utf-8'))
methods = json.loads((HERE / 'training-methods.json').read_text(encoding='utf-8'))
digest = hashlib.sha256(json.dumps([exercises, methods], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
version = '20260926-' + digest[:16]
OUT = HERE.parent.parent / '.dart_tool' / 'catalog-seed' / version
OUT.mkdir(parents=True, exist_ok=True)
method_batch = (len(exercises) + 74) // 75 + 1

def write(name, text):
    (OUT / name).write_text(text, encoding='utf-8')

def literal(data):
    value = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    assert '$catalog$' not in value
    return '$catalog$' + value + '$catalog$::jsonb'

write('000-release.sql', f"insert into public.catalog_releases(version, exercise_count, method_count) values ('{version}', {len(exercises)}, {len(methods)}) on conflict (version) do nothing;")
for batch, start in enumerate(range(0, len(exercises), 75), 1):
    rows = []
    for index, exercise in enumerate(exercises[start:start + 75], start):
        summary = dict(exercise)
        instructions = summary.pop('instructions', [])
        rows.append(dict(id=summary['id'], sort_order=index, summary=summary, instructions=instructions))
    write(f'{batch:03}-exercises.sql', f"""insert into public.catalog_exercises (release_version, id, sort_order, summary, instructions)
select '{version}', row->>'id', (row->>'sort_order')::integer, row->'summary', row->'instructions'
from jsonb_array_elements({literal(rows)}) as row
on conflict (release_version, id) do update set summary=excluded.summary, instructions=excluded.instructions, sort_order=excluded.sort_order;""")

rows = [dict(id=m['id'], sort_order=i, content=m) for i, m in enumerate(methods)]
write(f'{method_batch:03}-methods.sql', f"""insert into public.catalog_training_methods (release_version, id, sort_order, content)
select '{version}', row->>'id', (row->>'sort_order')::integer, row->'content'
from jsonb_array_elements({literal(rows)}) as row
on conflict (release_version, id) do update set content=excluded.content, sort_order=excluded.sort_order;""")
write(f'{method_batch + 1:03}-activate.sql', f"""begin;
do $verify$ begin
  if (select count(*) from public.catalog_exercises where release_version='{version}') <> {len(exercises)}
     or (select count(*) from public.catalog_training_methods where release_version='{version}') <> {len(methods)} then
    raise exception 'Incomplete catalog release';
  end if;
end $verify$;
update public.catalog_releases set active=false where active;
update public.catalog_releases set active=true where version='{version}';
commit;""")
write('manifest.json', json.dumps(dict(version=version, sha256=digest, exercises=len(exercises), methods=len(methods)), indent=2))
if '--migration' in sys.argv:
    migration = HERE.parent.parent.parent / 'supabase/migrations/20260927120000_catalog_gymvisual_exercises.sql'
    sql_files = sorted(OUT.glob('[0-9][0-9][0-9]-*.sql'))
    migration.write_text(
        '-- Generated by valex_app/tool/exercise_catalog/prepare_seed.py --migration.\n'
        '-- Publishes a complete new catalog release without changing saved workouts.\n'
        + '\n'.join(path.read_text(encoding='utf-8') for path in sql_files),
        encoding='utf-8',
    )
print(json.dumps(dict(version=version, exercises=len(exercises), methods=len(methods), summary_bytes=sum(len(json.dumps({k:v for k,v in x.items() if k != 'instructions'},ensure_ascii=False).encode()) for x in exercises)), indent=2))
